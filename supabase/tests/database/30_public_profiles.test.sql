begin;
create extension if not exists pgtap with schema extensions;
select no_plan();
create function pg_temp.public_user(p_name text) returns uuid language plpgsql as $$
declare uid uuid:=gen_random_uuid(); begin
  insert into auth.users(id,email,created_at,raw_user_meta_data) values(uid,uid::text||'@public-profile.test',now(),jsonb_build_object('display_name',p_name,'signup_kind','student','terms_accepted',true,'terms_version','2026-10-19-draft-1','privacy_version','2026-10-19-draft-1','age_declaration','adult')); return uid;
end $$;
create function pg_temp.public_login(uid uuid) returns void language plpgsql as $$ begin
  perform set_config('request.jwt.claim.sub',uid::text,true);
  perform set_config('request.jwt.claims',jsonb_build_object('sub',uid,'role','authenticated')::text,true);
end $$;
select set_config('pub.owner',pg_temp.public_user('Unique Public Learner')::text,true);
select set_config('pub.viewer',pg_temp.public_user('Profile Viewer')::text,true);
select set_config('pub.hidden',pg_temp.public_user('Deactivated Learner')::text,true);
update public.profiles set deactivated_at=now() where id=current_setting('pub.hidden')::uuid;
select pg_temp.public_login(current_setting('pub.viewer')::uuid);
set local role authenticated;
select is(public.get_public_profile_v1(current_setting('pub.owner')::uuid)->>'display_name','Unique Public Learner','another user can read the public identity');
select ok(not(public.get_public_profile_v1(current_setting('pub.owner')::uuid) ?| array['email','roles','premium','history','streak','learning_totals','leaderboard_visible']),'public response excludes private profile fields');
select is(jsonb_array_length(public.search_friends_v1('Unique Public')->'people'),1,'search finds display names');
select is(jsonb_array_length(public.search_friends_v1('UNIQUE PUBLIC')->'people'),1,'search is case insensitive');
select is(jsonb_array_length(public.search_friends_v1('Un')->'people'),0,'short search is bounded');
select throws_ok(format('select public.get_public_profile_v1(%L)',current_setting('pub.hidden')),'PT404','NOT_FOUND','deactivated target is unavailable');
select throws_ok('select public.get_public_profile_v1(null)','PT404','NOT_FOUND','null target is unavailable');
select is((select count(*)::int from public.profiles where id=current_setting('pub.owner')::uuid),0,'public access does not broaden private table policy');
select lives_ok('select public.update_profile_v1(p_display_name=>''Viewer Changed'')','owner can still update their own profile');
select is(public.get_public_profile_v1(current_setting('pub.owner')::uuid)->>'display_name','Unique Public Learner','owner mutation does not change another user');
reset role;
update public.profiles set leaderboard_visible=false where id=current_setting('pub.owner')::uuid;
insert into private.xp_badges(user_id,code) values(current_setting('pub.owner')::uuid,'first_steps');
set local role service_role;
select set_config('pub.photo',public.service_set_profile_photo_v1(current_setting('pub.owner')::uuid,'UklGRgAAAABXRUJQ',null)->>'avatar_path',true);
reset role;
set local role authenticated;
select is(public.get_public_profile_v1(current_setting('pub.owner')::uuid)->>'xp_total',null::text,'hidden leaderboard XP stays private');
select is(public.get_public_profile_v1(current_setting('pub.owner')::uuid)->'badges','["first_steps"]'::jsonb,'public badges are included');
select lives_ok(format('select public.get_public_profile_photo_v1(%L)',current_setting('pub.photo')),'public profile photo is independent of leaderboard visibility');
select is(jsonb_array_length(public.search_friends_v1('@'||(public.get_public_profile_v1(current_setting('pub.owner')::uuid)->>'username'))->'people'),1,'search accepts username with @');
reset role;
insert into public.friendships(user_low,user_high,actor_id,state) values(least(current_setting('pub.owner')::uuid,current_setting('pub.viewer')::uuid),greatest(current_setting('pub.owner')::uuid,current_setting('pub.viewer')::uuid),current_setting('pub.owner')::uuid,'blocked');
set local role authenticated;
select throws_ok(format('select public.get_public_profile_v1(%L)',current_setting('pub.owner')),'PT404','NOT_FOUND','blocked direct profile access denied');
select throws_ok(format('select public.get_public_profile_photo_v1(%L)',current_setting('pub.photo')),'PT404','NOT_FOUND','blocked photo access denied');
select is(jsonb_array_length(public.search_friends_v1('Unique Public')->'people'),0,'blocked accounts excluded from search');
select pg_temp.public_login(current_setting('pub.owner')::uuid);
select throws_ok(format('select public.get_public_profile_v1(%L)',current_setting('pub.viewer')),'PT404','NOT_FOUND','block is enforced in both directions');
reset role;
update public.profiles set deactivated_at=now() where id=current_setting('pub.viewer')::uuid;
select pg_temp.public_login(current_setting('pub.viewer')::uuid);
set local role authenticated;
select throws_ok(format('select public.get_public_profile_v1(%L)',current_setting('pub.owner')),'PT403','FORBIDDEN','deactivated viewer denied');
reset role;
select ok(not has_function_privilege('anon','public.get_public_profile_v1(uuid)','execute'),'anonymous profile access denied');
select ok(not has_function_privilege('anon','public.get_public_profile_photo_v1(text)','execute'),'anonymous photo access denied');
select * from finish();
rollback;
