begin;
create extension if not exists pgtap with schema extensions;
select no_plan();
create function pg_temp.photo_user() returns uuid language plpgsql as $$ declare id uuid:=gen_random_uuid();begin
 insert into auth.users(id,email,created_at,raw_user_meta_data) values(id,id::text||'@photos.test',now(),'{"display_name":"Photo test"}');return id;end $$;
create function pg_temp.photo_login(id uuid) returns void language plpgsql as $$ begin
 perform set_config('request.jwt.claim.sub',id::text,true);perform set_config('request.jwt.claims',jsonb_build_object('sub',id,'role','authenticated')::text,true);end $$;
select set_config('p.owner',pg_temp.photo_user()::text,true);
select set_config('p.viewer',pg_temp.photo_user()::text,true);
select set_config('p.admin',pg_temp.photo_user()::text,true);
insert into public.user_roles(user_id,role) values(current_setting('p.admin')::uuid,'admin');
select set_config('p.bytes',encode(decode('524946460000000057454250','hex'),'base64'),true);
select pg_temp.photo_login(current_setting('p.owner')::uuid);
set local role authenticated;
select throws_ok(format('select public.service_set_profile_photo_v1(%L,%L,null)',current_setting('p.owner'),current_setting('p.bytes')),'42501',null,'browser cannot call privileged photo writer');
select throws_ok('select * from private.profile_photos','42501',null,'browser cannot access private image table');
select throws_ok(format('select public.update_profile_v1(p_avatar_path=>%L)','avatars/someone-else/fake.webp'),'PT422','VALIDATION_FAILED','profile update cannot select a foreign or invented image');
reset role;
set local role service_role;
select set_config('p.path',public.service_set_profile_photo_v1(current_setting('p.owner')::uuid,current_setting('p.bytes'),null)->>'avatar_path',true);
reset role;
select is((select count(*)::int from private.profile_photos where user_id=current_setting('p.owner')::uuid),1,'one private image stored');
select ok(current_setting('p.path') like 'avatars/'||current_setting('p.owner')||'/%','path is bound to owner');
select pg_temp.photo_login(current_setting('p.owner')::uuid);
set local role authenticated;
select is(public.get_profile_photo_v1(current_setting('p.path'))->>'content_type','image/webp','owner can view saved WebP');
select is(public.get_profile_photo_v1(current_setting('p.path'))->>'width','512','standard width');
select is(public.get_profile_photo_v1(current_setting('p.path'))->>'height','512','standard height');
select pg_temp.photo_login(current_setting('p.viewer')::uuid);
select lives_ok(format('select public.get_profile_photo_v1(%L)',current_setting('p.path')),'visible student avatar can be read by another active user');
reset role;
update public.profiles set leaderboard_visible=false where id=current_setting('p.owner')::uuid;
set local role authenticated;
select throws_ok(format('select public.get_profile_photo_v1(%L)',current_setting('p.path')),'PT404','NOT_FOUND','hidden photo is not exposed to unrelated users');
select pg_temp.photo_login(current_setting('p.admin')::uuid);
select lives_ok(format('select public.get_profile_photo_v1(%L)',current_setting('p.path')),'administrator can view hidden photo');
reset role;
update public.profiles set deactivated_at=now() where id=current_setting('p.viewer')::uuid;
select pg_temp.photo_login(current_setting('p.viewer')::uuid);
set local role authenticated;
select throws_ok(format('select public.get_profile_photo_v1(%L)',current_setting('p.path')),'PT403','FORBIDDEN','frozen viewer cannot read images');
reset role;
set local role service_role;
select throws_ok(format('select public.service_set_profile_photo_v1(%L,%L,null)',current_setting('p.owner'),current_setting('p.bytes')),'PT409','STALE_REVISION','stale upload does not overwrite current image');
select throws_ok(format('select public.service_set_profile_photo_v1(%L,%L,%L)',current_setting('p.owner'),encode('invalid'::bytea,'base64'),current_setting('p.path')),'PT422','VALIDATION_FAILED','invalid binary rejected');
select set_config('p.new_path',public.service_set_profile_photo_v1(current_setting('p.owner')::uuid,current_setting('p.bytes'),current_setting('p.path'))->>'avatar_path',true);
reset role;
select is((select count(*)::int from private.profile_photos where user_id=current_setting('p.owner')::uuid),1,'replacement retains only one image');
select ok(current_setting('p.new_path')<>current_setting('p.path'),'replacement gets a new version');
select pg_temp.photo_login(current_setting('p.owner')::uuid);
set local role authenticated;
select throws_ok(format('select public.get_profile_photo_v1(%L)',current_setting('p.path')),'PT404','NOT_FOUND','old image URL stops resolving');
select lives_ok('select public.update_profile_v1(p_clear_avatar=>true)','legacy clear photo also removes private bytes');
reset role;
select is((select count(*)::int from private.profile_photos where user_id=current_setting('p.owner')::uuid),0,'removal leaves no binary');
select is((select avatar_path from public.profiles where id=current_setting('p.owner')::uuid),null::text,'removal clears profile reference');
set local role service_role;
select set_config('p.final_path',public.service_set_profile_photo_v1(current_setting('p.owner')::uuid,current_setting('p.bytes'),null)->>'avatar_path',true);
reset role;
update public.profiles set deactivated_at=now() where id=current_setting('p.owner')::uuid;
set local role service_role;
select throws_ok(format('select public.service_set_profile_photo_v1(%L,%L,%L)',current_setting('p.owner'),current_setting('p.bytes'),current_setting('p.final_path')),'PT403','FORBIDDEN','frozen owner cannot replace image');
reset role;
delete from auth.users where id=current_setting('p.owner')::uuid;
select is((select count(*)::int from private.profile_photos where user_id=current_setting('p.owner')::uuid),0,'account erasure removes photo atomically');
select pg_temp.photo_login(current_setting('p.admin')::uuid);
set local role authenticated;
select throws_ok(format('select public.get_profile_photo_v1(%L)',current_setting('p.final_path')),'PT404','NOT_FOUND','deleted account photo no longer readable');
reset role;
select ok(not has_function_privilege('anon','public.get_profile_photo_v1(text)','execute'),'anonymous readers denied');
select ok(not has_function_privilege('authenticated','public.service_set_profile_photo_v1(uuid,text,text)','execute'),'browser writer denied');
select * from finish();
rollback;
