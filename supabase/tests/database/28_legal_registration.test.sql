-- Run against the complete local Supabase schema. No synthetic legal fixture trigger.
begin;
create extension if not exists pgtap with schema extensions;
select no_plan();
create function pg_temp.register_legal(p_email text,p_meta jsonb) returns uuid language plpgsql as $$
declare uid uuid:=gen_random_uuid();
begin
  insert into auth.users(id,email,raw_user_meta_data) values(uid,p_email,p_meta);
  return uid;
end $$;
create function pg_temp.adult_meta() returns jsonb language sql as $$
  select jsonb_build_object('display_name','Legal test','terms_accepted',true,
    'terms_version','2026-10-19-draft-1','privacy_version','2026-10-19-draft-1','age_declaration','adult')
$$;
select is((public.get_registration_legal_status_v1()->>'guardian_enabled')::boolean,false,'Guardian registration is closed by default');
select throws_ok($$select pg_temp.register_legal('missing@legal.test','{}')$$,'P0001','LEGAL_ACCEPTANCE_REQUIRED','Direct signup requires legal metadata');
select throws_ok($$select pg_temp.register_legal('unchecked@legal.test',pg_temp.adult_meta()||'{"terms_accepted":false}')$$,'P0001','LEGAL_ACCEPTANCE_REQUIRED','Unchecked terms are rejected');
select throws_ok($$select pg_temp.register_legal('stale@legal.test',pg_temp.adult_meta()||'{"terms_version":"old"}')$$,'P0001','LEGAL_ACCEPTANCE_REQUIRED','Stale policy versions are rejected');
select set_config('legal_test.minor',pg_temp.register_legal('minor@legal.test',pg_temp.adult_meta()||'{"age_declaration":"under18"}')::text,true);
select is((select age_declaration from private.legal_acceptances where user_id=current_setting('legal_test.minor')::uuid),'adult','Age group is not collected; acceptance is recorded as adult');
select set_config('legal_test.adult',pg_temp.register_legal('adult@legal.test',pg_temp.adult_meta())::text,true);
select is((select age_declaration from private.legal_acceptances where user_id=current_setting('legal_test.adult')::uuid),'adult','Adult acceptance is recorded');
select ok((select accepted_at>now()-interval '1 minute' from private.legal_acceptances where user_id=current_setting('legal_test.adult')::uuid),'Timestamp is generated by the database');
select ok(not exists(select 1 from auth.users where email in ('missing@legal.test','unchecked@legal.test','stale@legal.test')),'Rejected registrations leave no Auth accounts');
delete from auth.users where id=current_setting('legal_test.minor')::uuid;
select set_config('request.jwt.claim.sub',current_setting('legal_test.adult'),true);
set local role authenticated;
select throws_ok('select * from private.guardian_consents','42501',null,'Students cannot read guardian records');
select throws_ok('select public.admin_list_guardian_requests_v1()','42501','Active administrator required','Students cannot invoke guardian administration');
reset role;
delete from auth.users where id=current_setting('legal_test.adult')::uuid;
select is((select count(*)::int from private.legal_acceptances where user_id=current_setting('legal_test.adult')::uuid),0,'Full erasure removes acceptance');
select * from finish();
rollback;
